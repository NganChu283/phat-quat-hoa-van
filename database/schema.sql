CREATE DATABASE IF NOT EXISTS phat_quat_hoa_van CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE phat_quat_hoa_van;
CREATE TABLE IF NOT EXISTS posts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL, excerpt VARCHAR(500) NOT NULL,
 show_on_home TINYINT(1) NOT NULL DEFAULT 0,
 body_format VARCHAR(10) NOT NULL DEFAULT 'plain',
 body MEDIUMTEXT NOT NULL, image VARCHAR(255) NOT NULL DEFAULT 'assets/village.jpg',
 published TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS gallery (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL, image VARCHAR(255) NOT NULL,
 category VARCHAR(40) NOT NULL DEFAULT 'Quạt Chàng Sơn',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS registrations (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL, phone VARCHAR(25) NOT NULL,
 activity VARCHAR(60) NOT NULL, message TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS contacts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL,
 message TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- Bổ sung cho database đang có. Có thể chạy lại, không xóa dữ liệu.
CREATE TABLE IF NOT EXISTS projects (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL,
 subtitle VARCHAR(180) NOT NULL DEFAULT '',
 starts_at DATETIME NULL,
 description VARCHAR(500) NOT NULL DEFAULT '',
 published TINYINT(1) NOT NULL DEFAULT 1,
 ends_at DATETIME NULL,
 venue VARCHAR(180) NOT NULL DEFAULT '',
 address VARCHAR(500) NOT NULL DEFAULT '',
 schedule TEXT NULL,
 featured TINYINT UNSIGNED NULL DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY one_featured_project (featured)
);

CREATE TABLE IF NOT EXISTS mail_queue (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 registration_id INT UNSIGNED NOT NULL,
 recipient VARCHAR(254) NOT NULL,
 subject VARCHAR(255) NOT NULL, body TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0, last_error VARCHAR(255) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, sent_at DATETIME NULL,
 INDEX (registration_id), INDEX (status)
);
CREATE TABLE IF NOT EXISTS form_limits (
 fingerprint CHAR(64) PRIMARY KEY, window_started BIGINT NOT NULL, attempts INT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 display_name VARCHAR(120) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','editor') NOT NULL DEFAULT 'editor',
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 auth_version INT UNSIGNED NOT NULL DEFAULT 1,
 last_login_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS app_migrations (
 name VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS story_settings (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 published TINYINT(1) NOT NULL DEFAULT 1,
 sort_order INT NOT NULL DEFAULT 0,
 eyebrow VARCHAR(120) NOT NULL,
 title VARCHAR(180) NOT NULL,
 title_accent VARCHAR(180) NOT NULL,
 intro VARCHAR(2000) NOT NULL,
 image VARCHAR(255) NOT NULL,
 image_alt VARCHAR(180) NOT NULL,
 image_caption VARCHAR(255) NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS story_sections (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL, body MEDIUMTEXT NOT NULL,
 body_format VARCHAR(10) NOT NULL DEFAULT 'plain',
 published TINYINT(1) NOT NULL DEFAULT 1,
 sort_order INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
